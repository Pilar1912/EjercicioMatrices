public class ObjMatriz {
    int dato;

    //Constructor
    public ObjMatriz(int dato) {
        this.dato = dato;
    }

    //Constructor vacío
    public ObjMatriz() {
    }

    //Método de acceso
    public int getDato() {
        return dato;
    }

    //Método de modificación
    public void setDato(int dato) {
        this.dato = dato;
    }
    
}